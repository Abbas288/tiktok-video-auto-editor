export function createGoogleAiStudioTemplatePrompt(): string {
  return [
    "You are generating a JSON template for a React Native video editor.",
    "",
    "Task:",
    "Analyze the provided TikTok or video URL and return one strict JSON object that matches the editor schema below.",
    "",
    "Rules:",
    "1. Return JSON only.",
    "2. Do not wrap the response in markdown.",
    "3. Do not add comments.",
    "4. Use double quotes only.",
    "5. Create ordered scene timings that cover the video.",
    "6. Each scene instruction must clearly tell the user what kind of clip should be uploaded.",
    "7. Use textOverlays only when text should appear in the final video.",
    "8. Use effects only when they improve the edit.",
    "9. Use transitions only between scenes.",
    "",
    "Required top-level fields:",
    "- id: string",
    "- title: string",
    "- sourceVideoUrl: string",
    "- orientation: portrait, landscape or square",
    "- scenes: non-empty array",
    "",
    "Required scene fields:",
    "- id: string",
    "- orderIndex: number",
    "- startSeconds: number",
    "- durationSeconds: positive number",
    "- instruction: string",
    "- textOverlays: array",
    "- effects: array",
    "- transition: optional object",
    "",
    "Text overlay fields:",
    "- id: string",
    "- text: string",
    "- positionX: number from 0 to 1",
    "- positionY: number from 0 to 1",
    "- fontSizePt: positive number",
    "- color: hex color string",
    "- style: normal, bold or italic",
    "- animationIn: none, fadeUp or fadeIn",
    "- startSeconds: number",
    "- durationSeconds: positive number",
    "",
    "Effect examples:",
    '{ "type": "brightness", "value": 1.1 }',
    '{ "type": "contrast", "value": 1.2 }',
    '{ "type": "zoom", "intensity": 1.3, "positionX": 0.5, "positionY": 0.5 }',
    "",
    "Transition examples:",
    '{ "type": "cut", "durationSeconds": 0 }',
    '{ "type": "fade", "durationSeconds": 0.18 }',
    '{ "type": "slide", "durationSeconds": 0.18, "direction": "left" }',
    "",
    "Return JSON in this exact shape:",
    "{",
    '  "id": "short-template-id",',
    '  "title": "Template title",',
    '  "sourceVideoUrl": "PASTE_VIDEO_URL_HERE",',
    '  "orientation": "portrait",',
    '  "originalVolume": 1,',
    '  "scenes": [',
    "    {",
    '      "id": "scene-1",',
    '      "orderIndex": 0,',
    '      "startSeconds": 0,',
    '      "durationSeconds": 3,',
    '      "instruction": "Describe what the user should upload for this scene.",',
    '      "transition": {',
    '        "type": "cut",',
    '        "durationSeconds": 0',
    "      },",
    '      "textOverlays": [],',
    '      "effects": []',
    "    }",
    "  ]",
    "}",
    "",
    "Video URL to analyze:",
    "PASTE_TIKTOK_OR_VIDEO_URL_HERE",
  ].join("\n");
}
